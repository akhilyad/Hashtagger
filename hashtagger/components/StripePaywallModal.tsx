'use client';

import React, { useState, useEffect } from 'react';
import { useRouter } from 'next/navigation';
import {
  ShieldCheck,
  X,
  CreditCard,
  Lock,
  Sparkles,
  Check,
  ArrowRight,
  Loader2,
  Zap,
} from 'lucide-react';
import {
  PlanTierId,
  BillingCycle,
  PRICING_PLANS,
  InvoiceRecord,
} from '@/lib/hashtag-data';
import {
  getCurrency,
  convertEurAmount,
  formatCurrencyPrice,
} from '@/lib/currency';
import { useHashtaggerStore } from '@/lib/use-hashtagger-store';
import CurrencySelector from '@/components/CurrencySelector';

interface StripePaywallModalProps {
  isOpen: boolean;
  onClose: () => void;
  initialPlan?: PlanTierId;
  reason?: string;
}

export default function StripePaywallModal({
  isOpen,
  onClose,
  initialPlan = 'pro',
  reason,
}: StripePaywallModalProps) {
  const router = useRouter();
  const {
    billingCycle,
    setBillingCycle,
    selectedCurrency,
    setSelectedCurrency,
    invoices,
    saveSubscription,
  } = useHashtaggerStore();

  const [selectedPlanId, setSelectedPlanId] = useState<PlanTierId>(
    initialPlan === 'free' ? 'pro' : initialPlan
  );
  const [customerName, setCustomerName] = useState('Alex Rivera');
  const [customerEmail, setCustomerEmail] = useState('alex@creatorstudio.io');
  const [cardNumber, setCardNumber] = useState('4242 •••• •••• 4242');
  const [cardExpiry, setCardExpiry] = useState('12/28');
  const [cardCvc, setCardCvc] = useState('888');
  const [isLoading, setIsLoading] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  // Sync initial plan if prop changes
  useEffect(() => {
    if (initialPlan && initialPlan !== 'free') {
      setSelectedPlanId(initialPlan);
    }
  }, [initialPlan]);

  // Handle escape key
  useEffect(() => {
    function handleKeyDown(e: KeyboardEvent) {
      if (e.key === 'Escape' && isOpen) {
        onClose();
      }
    }
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isOpen, onClose]);

  if (!isOpen) return null;

  const plan = PRICING_PLANS[selectedPlanId];
  const curr = getCurrency(selectedCurrency);

  // EUR base calculations
  const eurPerMonth =
    billingCycle === 'annual' ? plan.annualPricePerMonth : plan.monthlyPrice;
  const eurTotalDue =
    billingCycle === 'annual' ? plan.annualPricePerMonth * 12 : plan.monthlyPrice;

  // Converted values
  const convertedPerMonth = convertEurAmount(eurPerMonth, selectedCurrency);
  const convertedTotalDue = convertEurAmount(eurTotalDue, selectedCurrency);
  const formattedTotalDisplay = formatCurrencyPrice(eurTotalDue, selectedCurrency, {
    withDecimals: true,
  });

  const handleQuickFillTestCard = () => {
    setCardNumber('4242 4242 4242 4242');
    setCardExpiry('12/28');
    setCardCvc('888');
    setCustomerName('Alex Rivera');
    setCustomerEmail('alex@creatorstudio.io');
  };

  const handleCheckoutSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMessage(null);

    if (!customerName.trim() || !customerEmail.includes('@')) {
      setErrorMessage('Please provide your full name and a valid email address.');
      return;
    }

    setIsLoading(true);

    try {
      // Call Stripe backend endpoint
      const response = await fetch('/api/stripe/checkout', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          planId: selectedPlanId,
          billingCycle,
          currency: selectedCurrency,
          customerEmail,
          customerName,
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.error || 'Stripe checkout initialization failed.');
      }

      // If a live Stripe checkout URL was generated by Stripe API
      if (data.isLiveStripe && data.url) {
        window.location.href = data.url;
        return;
      }

      // Simulated / development Stripe checkout flow
      // Simulate real bank authorization roundtrip
      await new Promise((res) => setTimeout(res, 900));

      const newInvoice: InvoiceRecord = {
        id: `STRIPE-${Math.floor(100000 + Math.random() * 900000)}`,
        date: new Date().toLocaleDateString('en-US', {
          month: 'short',
          day: 'numeric',
          year: 'numeric',
        }),
        planName: plan.name,
        billingCycle,
        amount: `${formattedTotalDisplay} / ${
          billingCycle === 'annual' ? 'yr' : 'mo'
        }`,
        status: 'Paid',
      };

      saveSubscription(
        selectedPlanId,
        billingCycle,
        9999,
        [newInvoice, ...invoices],
        selectedCurrency
      );

      setIsLoading(false);
      onClose();
      router.push(`/receipt?plan=${selectedPlanId}&currency=${selectedCurrency}`);
    } catch (err: any) {
      setIsLoading(false);
      setErrorMessage(
        err.message || 'Payment processing failed. Please check your details.'
      );
    }
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-950/70 backdrop-blur-sm flex items-center justify-center p-4 overflow-y-auto animate-in fade-in duration-200">
      <div className="bg-white border border-slate-200 rounded-2xl max-w-xl w-full p-6 sm:p-7 space-y-6 shadow-2xl relative my-8">
        {/* Close Button */}
        <button
          type="button"
          onClick={onClose}
          aria-label="Close Stripe Paywall"
          className="absolute top-5 right-5 text-slate-400 hover:text-slate-700 bg-slate-100 hover:bg-slate-200 p-1.5 rounded-full transition-colors cursor-pointer"
        >
          <X className="w-4 h-4" />
        </button>

        {/* Header with Stripe Branding */}
        <div className="space-y-2 pr-8">
          <div className="flex items-center gap-2">
            <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-semibold tracking-wide bg-indigo-50 text-indigo-700 border border-indigo-200/60">
              <Sparkles className="w-3 h-3 text-indigo-600" />
              <span>STRIPE PAYWALL</span>
            </span>
            <span className="text-[11px] font-medium text-emerald-700 bg-emerald-50 px-2 py-0.5 rounded-full border border-emerald-200/60 flex items-center gap-1">
              <Lock className="w-3 h-3 text-emerald-600" />
              256-bit Encrypted
            </span>
          </div>

          <h2
            className="text-2xl font-bold text-slate-950 tracking-tight"
            style={{ fontFamily: 'var(--font-display), sans-serif' }}
          >
            Unlock Unlimited High-Reach Hashtags
          </h2>

          {reason ? (
            <div className="p-2.5 rounded-lg bg-amber-50 border border-amber-200 text-amber-900 text-xs flex items-center gap-2">
              <Zap className="w-4 h-4 text-amber-600 shrink-0" />
              <span>{reason}</span>
            </div>
          ) : (
            <p className="text-xs text-slate-600">
              Supercharge your social strategy with unlimited multimodal AI post
              scans, real-time live trends, and instant CSV exports.
            </p>
          )}
        </div>

        {/* Currency & Cycle Controls Bar */}
        <div className="p-3.5 bg-slate-50 border border-slate-200/90 rounded-xl space-y-3">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
            {/* Currency Selector */}
            <CurrencySelector
              value={selectedCurrency}
              onChange={setSelectedCurrency}
              size="sm"
            />

            {/* Billing Cycle Toggle */}
            <div>
              <span className="block text-[11px] font-medium text-slate-500 mb-1">
                Billing Cadence
              </span>
              <div className="inline-flex p-0.5 bg-slate-200/80 rounded-lg text-xs font-medium">
                <button
                  type="button"
                  onClick={() => setBillingCycle('monthly')}
                  className={`px-3 py-1 rounded-md transition-colors cursor-pointer ${
                    billingCycle === 'monthly'
                      ? 'bg-white text-slate-950 font-semibold shadow-xs'
                      : 'text-slate-600 hover:text-slate-950'
                  }`}
                >
                  Monthly
                </button>
                <button
                  type="button"
                  onClick={() => setBillingCycle('annual')}
                  className={`px-3 py-1 rounded-md transition-colors cursor-pointer ${
                    billingCycle === 'annual'
                      ? 'bg-white text-slate-950 font-semibold shadow-xs'
                      : 'text-slate-600 hover:text-slate-950'
                  }`}
                >
                  Annual · Save 20%
                </button>
              </div>
            </div>
          </div>
        </div>

        {/* Plan Selector Radio Cards */}
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
          {(['pro', 'agency'] as PlanTierId[]).map((tierId) => {
            const p = PRICING_PLANS[tierId];
            const isSelected = selectedPlanId === tierId;
            const pEurPerMonth =
              billingCycle === 'annual'
                ? p.annualPricePerMonth
                : p.monthlyPrice;
            const pDisplayPrice = formatCurrencyPrice(
              pEurPerMonth,
              selectedCurrency
            );

            return (
              <button
                key={tierId}
                type="button"
                onClick={() => setSelectedPlanId(tierId)}
                className={`p-4 rounded-xl border text-left transition-all cursor-pointer relative flex flex-col justify-between ${
                  isSelected
                    ? 'border-indigo-600 bg-indigo-50/20 ring-1 ring-indigo-600 shadow-sm'
                    : 'border-slate-200 bg-white hover:border-slate-300'
                }`}
              >
                {tierId === 'pro' && (
                  <span className="absolute -top-2.5 right-3 bg-indigo-600 text-white text-[10px] font-bold px-2 py-0.5 rounded-full uppercase tracking-wider">
                    Recommended
                  </span>
                )}
                <div>
                  <div className="flex items-center justify-between">
                    <span className="font-bold text-slate-950 text-sm">
                      {p.name}
                    </span>
                    <span
                      className={`w-4 h-4 rounded-full border flex items-center justify-center ${
                        isSelected
                          ? 'border-indigo-600 bg-indigo-600 text-white'
                          : 'border-slate-300'
                      }`}
                    >
                      {isSelected && <Check className="w-3 h-3 stroke-[3]" />}
                    </span>
                  </div>
                  <div className="mt-2 flex items-baseline gap-1">
                    <span className="text-xl font-bold font-mono text-slate-950">
                      {pDisplayPrice}
                    </span>
                    <span className="text-[11px] text-slate-500">/ mo</span>
                  </div>
                  <p className="text-[11px] text-slate-600 mt-1 line-clamp-2">
                    {p.summary}
                  </p>
                </div>
              </button>
            );
          })}
        </div>

        {/* Feature Highlights of selected plan */}
        <div className="bg-slate-50/70 p-3.5 rounded-xl border border-slate-100">
          <span className="text-[11px] font-semibold uppercase tracking-wider text-slate-400 block mb-2">
            What you unlock instantly:
          </span>
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 text-xs text-slate-700">
            {plan.highlights.slice(0, 4).map((feat, i) => (
              <div key={i} className="flex items-start gap-1.5">
                <Check className="w-3.5 h-3.5 text-indigo-600 shrink-0 mt-0.5" />
                <span className="text-[11px] leading-tight">{feat}</span>
              </div>
            ))}
          </div>
        </div>

        {/* Stripe Payment Form */}
        <form onSubmit={handleCheckoutSubmit} className="space-y-4">
          <div className="flex items-center justify-between pb-1">
            <span className="text-xs font-semibold text-slate-800 flex items-center gap-1.5">
              <CreditCard className="w-4 h-4 text-indigo-600" />
              <span>Card Details (Stripe Checkout)</span>
            </span>
            <button
              type="button"
              onClick={handleQuickFillTestCard}
              className="text-[11px] font-mono text-indigo-600 hover:text-indigo-800 hover:underline cursor-pointer"
            >
              Fill Test Card
            </button>
          </div>

          <div className="space-y-3">
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
              <div>
                <label className="block text-[11px] font-medium text-slate-600 mb-1">
                  Cardholder Name
                </label>
                <input
                  type="text"
                  required
                  value={customerName}
                  onChange={(e) => setCustomerName(e.target.value)}
                  className="w-full px-3 py-2 text-xs rounded-lg border border-slate-200 bg-white focus:border-indigo-600 focus:outline-none"
                  placeholder="Full Name"
                />
              </div>

              <div>
                <label className="block text-[11px] font-medium text-slate-600 mb-1">
                  Receipt Email
                </label>
                <input
                  type="email"
                  required
                  value={customerEmail}
                  onChange={(e) => setCustomerEmail(e.target.value)}
                  className="w-full px-3 py-2 text-xs rounded-lg border border-slate-200 bg-white focus:border-indigo-600 focus:outline-none"
                  placeholder="name@company.com"
                />
              </div>
            </div>

            <div>
              <label className="block text-[11px] font-medium text-slate-600 mb-1">
                Card Number
              </label>
              <div className="relative">
                <CreditCard className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
                <input
                  type="text"
                  required
                  value={cardNumber}
                  onChange={(e) => setCardNumber(e.target.value)}
                  className="w-full pl-9 pr-12 py-2 text-xs font-mono rounded-lg border border-slate-200 bg-white focus:border-indigo-600 focus:outline-none"
                  placeholder="4242 •••• •••• 4242"
                />
                <span className="absolute right-3 top-1/2 -translate-y-1/2 text-[10px] font-bold text-slate-400 uppercase tracking-wider">
                  STRIPE
                </span>
              </div>
            </div>

            <div className="grid grid-cols-2 gap-2.5">
              <div>
                <label className="block text-[11px] font-medium text-slate-600 mb-1">
                  Expires (MM/YY)
                </label>
                <input
                  type="text"
                  required
                  value={cardExpiry}
                  onChange={(e) => setCardExpiry(e.target.value)}
                  className="w-full px-3 py-2 text-xs font-mono rounded-lg border border-slate-200 bg-white focus:border-indigo-600 focus:outline-none"
                  placeholder="12/28"
                />
              </div>
              <div>
                <label className="block text-[11px] font-medium text-slate-600 mb-1">
                  Security Code (CVC)
                </label>
                <input
                  type="text"
                  required
                  value={cardCvc}
                  onChange={(e) => setCardCvc(e.target.value)}
                  className="w-full px-3 py-2 text-xs font-mono rounded-lg border border-slate-200 bg-white focus:border-indigo-600 focus:outline-none"
                  placeholder="888"
                />
              </div>
            </div>
          </div>

          {errorMessage && (
            <p className="text-xs text-red-600 bg-red-50 p-2.5 rounded-lg border border-red-200">
              {errorMessage}
            </p>
          )}

          {/* Pricing Summary Box */}
          <div className="p-3.5 rounded-xl bg-slate-900 text-white flex items-center justify-between text-xs">
            <div>
              <span className="text-slate-300 font-medium block">
                Total Due Today ({plan.name})
              </span>
              <span className="text-[11px] text-slate-400">
                {billingCycle === 'annual'
                  ? `Annual billing (${formattedTotalDisplay}/yr)`
                  : `Monthly billing (${formattedTotalDisplay}/mo)`}{' '}
                · Currency: {curr.code} ({curr.symbol})
              </span>
            </div>
            <div className="text-right">
              <span className="text-xl font-bold font-mono tabular-nums text-white block">
                {formattedTotalDisplay}
              </span>
              <span className="text-[10px] text-emerald-400 font-mono">
                No hidden fees
              </span>
            </div>
          </div>

          {/* Primary Action Button */}
          <button
            type="submit"
            disabled={isLoading}
            className="w-full py-3 px-5 text-sm font-semibold text-white bg-indigo-600 hover:bg-indigo-700 active:bg-indigo-800 disabled:opacity-70 rounded-xl transition-all shadow-md hover:shadow-indigo-500/25 cursor-pointer flex items-center justify-center gap-2"
          >
            {isLoading ? (
              <>
                <Loader2 className="w-4 h-4 animate-spin" />
                <span>Authorizing with Stripe...</span>
              </>
            ) : (
              <>
                <ShieldCheck className="w-4 h-4" />
                <span>
                  Pay {formattedTotalDisplay} via Stripe &amp; Unlock
                </span>
                <ArrowRight className="w-4 h-4 ml-1" />
              </>
            )}
          </button>

          {/* Guarantee Footer */}
          <div className="flex items-center justify-center gap-4 pt-1 text-[11px] text-slate-400">
            <span className="flex items-center gap-1">
              <Lock className="w-3 h-3 text-slate-400" />
              <span>Stripe 3D Secure</span>
            </span>
            <span>•</span>
            <span>14-day money-back guarantee</span>
            <span>•</span>
            <span>Cancel anytime</span>
          </div>
        </form>
      </div>
    </div>
  );
}

